-- MySQL 8.0+ / Helpdesk - equipment and equipment_assignments
-- Additive script: does not drop or modify existing users, locations, products, tickets, orders.
-- Prerequisites: helpdesk.users, helpdesk.locations, helpdesk.products with referenced IDs.
-- The equipment_assignments type has no seed list in the supplied file; the table starts empty.
-- Columns follow SQL snake_case convention; assigned_to corresponds to TS assignedTo.
USE `helpdesk`;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `equipment` (
  `id` VARCHAR(20) NOT NULL,
  `product_id` VARCHAR(20) NOT NULL,
  `asset_tag` VARCHAR(100) NOT NULL,
  `serial_number` VARCHAR(150) NOT NULL,
  `status` ENUM('available','reserved','assigned','in_repair','lost','retired') NOT NULL,
  `assigned_to` VARCHAR(20) NULL,
  `location_id` VARCHAR(20) NOT NULL,
  `room` VARCHAR(150) NULL,
  `purchase_date` DATE NOT NULL,
  `warranty_until` DATE NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_equipment_asset_tag` (`asset_tag`),
  UNIQUE KEY `uq_equipment_serial_number` (`serial_number`),
  KEY `idx_equipment_product` (`product_id`),
  KEY `idx_equipment_assigned_to` (`assigned_to`),
  KEY `idx_equipment_location` (`location_id`),
  KEY `idx_equipment_status` (`status`),
  CONSTRAINT `fk_equipment_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_equipment_assigned_to` FOREIGN KEY (`assigned_to`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_equipment_location` FOREIGN KEY (`location_id`) REFERENCES `locations` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `equipment_assignments` (
  `id` VARCHAR(20) NOT NULL,
  `equipment_id` VARCHAR(20) NOT NULL,
  `ticket_id` VARCHAR(20) NULL,
  `user_id` VARCHAR(20) NULL,
  `technician_id` VARCHAR(20) NULL,
  `status` ENUM('reserved','assigned','returned','cancelled') NOT NULL,
  `reserved_at` DATETIME(3) NULL,
  `assigned_at` DATETIME(3) NULL,
  `returned_at` DATETIME(3) NULL,
  `cancelled_at` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  KEY `idx_assignment_equipment` (`equipment_id`),
  KEY `idx_assignment_ticket` (`ticket_id`),
  KEY `idx_assignment_user` (`user_id`),
  KEY `idx_assignment_technician` (`technician_id`),
  KEY `idx_assignment_status` (`status`),
  CONSTRAINT `fk_assignment_equipment` FOREIGN KEY (`equipment_id`) REFERENCES `equipment` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_assignment_ticket` FOREIGN KEY (`ticket_id`) REFERENCES `tickets` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_assignment_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_assignment_technician` FOREIGN KEY (`technician_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

